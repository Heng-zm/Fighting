try {
  fs.mkdirSync(path.join(heroDir, 'sprites'), { recursive: true });
  fs.mkdirSync(path.join(heroDir, 'icons'), { recursive: true });
  fs.mkdirSync(path.join(heroDir, 'sounds'), { recursive: true });
  fs.writeFileSync(path.join(heroDir, 'character.json'), JSON.stringify(character, null, 2) + '\n', 'utf8');
  fs.writeFileSync(path.join(heroDir, 'skills.js'), skillsStub, 'utf8');
  // 4 template skills are in character.json; this file documents their ids.
  fs.writeFileSync(
    path.join(heroDir, 'SKILLS.md'),
    `# ${displayName} skills\n\n` +
      skills.map((skill) => `- **${skill.slot} / ${skill.displayName}** — \`${skill.id}\` (${skill.type})`).join('\n') +
      `\n\nEdit \`character.json\` to tune values. Override individual skill ids in \`skills.js\`.\n`,
    'utf8'
  );
} catch (error) {
  fail(`Could not create character: ${error.message}`);
}

