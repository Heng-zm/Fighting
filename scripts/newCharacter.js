/**
 * CLI: npm run new-character <name>
 *
 * Creates a fully valid character folder with four template skills, a custom
 * skill stub and empty asset folders. The next server start discovers it
 * automatically and generates placeholder art for any missing sprites/icons.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const CHARACTERS_DIR = path.join(ROOT, 'characters');

function fail(message) {
  console.error(`\n✖ ${message}\n`);
  process.exit(1);
}

const rawName = process.argv.slice(2).find((arg) => !arg.startsWith('-'));
if (!rawName) {
  fail('Usage: npm run new-character <name>\nExample: npm run new-character test');
}

const id = rawName.trim().toLowerCase().replace(/\s+/g, '-');
if (!/^[a-z0-9_-]{2,32}$/.test(id)) {
  fail('Character name must be 2-32 characters using letters, numbers, - or _.');
}

const displayName = id
  .split(/[-_]+/)
  .filter(Boolean)
  .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
  .join(' ');

const heroDir = path.join(CHARACTERS_DIR, id);
if (fs.existsSync(heroDir)) {
  fail(`character "${id}" already exists at characters/${id}.`);
}

